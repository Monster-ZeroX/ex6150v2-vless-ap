#!/usr/bin/env python3
"""Generate chacha_arm.s: scalar ChaCha20 for 32-bit ARM (Go assembler syntax).

Technique (as in the Linux kernel's chacha-scalar-core.S): rotations are deferred and
folded into the shifted operand of the next ADD/EOR, so a quarter round is 8 ALU ops.
Invariant between quarter rounds: every b word is stored as (true_b ROR 7) i.e. it
must be read as b@>25, every d word as (true_d ROR 8), read as d@>24.

Register map (R10 = g and R13 = SP are untouchable; R11 is safe: no pseudo-ops used):
  x0-x3 -> R0-R3   x4-x7 -> R4-R7   x12 R8  x13 R9  x14 R11  x15 R12
  x8-x11 live in the frame and pass through R14 one quarter round at a time.
Frame (offsets from R13; 0(R13) holds the saved LR):
  4 dst, 8 src, 12 blocks left, 16 state ptr, 20 double-round counter,
  24..39 x8..x11, 40..103 x0..x15 scratch for the feed-forward pass.
"""

A = {0: "R0", 1: "R1", 2: "R2", 3: "R3"}
B = {4: "R4", 5: "R5", 6: "R6", 7: "R7"}
D = {12: "R8", 13: "R9", 14: "R11", 15: "R12"}
C_OFF = {8: 24, 9: 28, 10: 32, 11: 36}


def qr(a, b, c, d):
    ra, rb, rd, co = A[a], B[b], D[d], C_OFF[c]
    return [
        f"\tADD\t{rb}@>25, {ra}",          # a += b
        f"\tEOR\t{rd}@>24, {ra}, {rd}",    # d = a ^ d          (pending rotl 16 = ror 16)
        f"\tMOVW\t{co}(R13), R14",         # c
        f"\tADD\t{rd}@>16, R14",           # c += d
        f"\tEOR\t{rb}@>25, R14, {rb}",     # b = c ^ b          (pending rotl 12 = ror 20)
        f"\tADD\t{rb}@>20, {ra}",          # a += b
        f"\tEOR\t{rd}@>16, {ra}, {rd}",    # d = a ^ d          (pending rotl 8 = ror 24)
        f"\tADD\t{rd}@>24, R14",           # c += d
        f"\tEOR\t{rb}@>20, R14, {rb}",     # b = c ^ b          (pending rotl 7 = ror 25)
        f"\tMOVW\tR14, {co}(R13)",
    ]


out = []
w = out.append
w("// Code generated by gen_chacha_arm.py for the EX6150v2 build. DO NOT EDIT.")
w("")
w("//go:build gc && !purego")
w("")
w('#include "textflag.h"')
w("")
w("// func xorKeyStreamARM(dst, src *byte, blocks int, state *[16]uint32)")
w("TEXT ·xorKeyStreamARM(SB), NOSPLIT, $112-16")
w("\tMOVW\tblocks+8(FP), R0")
w("\tCMP\t$0, R0")
w("\tBEQ\tdone")
w("\tMOVW\tR0, 12(R13)")
w("\tMOVW\tdst+0(FP), R0")
w("\tMOVW\tR0, 4(R13)")
w("\tMOVW\tsrc+4(FP), R0")
w("\tMOVW\tR0, 8(R13)")
w("\tMOVW\tstate+12(FP), R0")
w("\tMOVW\tR0, 16(R13)")
w("")
w("block:")
w("\tMOVW\t16(R13), R14")
for i in range(8, 12):
    w(f"\tMOVW\t{4 * i}(R14), R0")
    w(f"\tMOVW\tR0, {C_OFF[i]}(R13)")
for i in range(4):
    w(f"\tMOVW\t{4 * i}(R14), {A[i]}")
for i in range(4, 8):
    w(f"\tMOVW\t{4 * i}(R14), {B[i]}")
for i in range(12, 16):
    w(f"\tMOVW\t{4 * i}(R14), {D[i]}")
w("\t// establish the deferred-rotation invariant")
for i in range(4, 8):
    w(f"\tMOVW\t{B[i]}@>7, {B[i]}")
for i in range(12, 16):
    w(f"\tMOVW\t{D[i]}@>8, {D[i]}")
w("\tMOVW\t$10, R14")
w("\tMOVW\tR14, 20(R13)")
w("")
w("round:")
w("\t// column round")
for a, b, c, d in [(0, 4, 8, 12), (1, 5, 9, 13), (2, 6, 10, 14), (3, 7, 11, 15)]:
    out.extend(qr(a, b, c, d))
w("\t// diagonal round")
for a, b, c, d in [(0, 5, 10, 15), (1, 6, 11, 12), (2, 7, 8, 13), (3, 4, 9, 14)]:
    out.extend(qr(a, b, c, d))
w("\tMOVW\t20(R13), R14")
w("\tSUB.S\t$1, R14")
w("\tMOVW\tR14, 20(R13)")
w("\tBNE\tround")
w("")
w("\t// undo deferred rotations, park the working state in the frame")
for i in range(4):
    w(f"\tMOVW\t{A[i]}, {40 + 4 * i}(R13)")
for i in range(4, 8):
    w(f"\tMOVW\t{B[i]}@>25, {B[i]}")
    w(f"\tMOVW\t{B[i]}, {40 + 4 * i}(R13)")
for i in range(12, 16):
    w(f"\tMOVW\t{D[i]}@>24, {D[i]}")
    w(f"\tMOVW\t{D[i]}, {40 + 4 * i}(R13)")
w("")
w("\t// feed-forward and XOR, one word at a time (LDR/STR tolerate unaligned on ARMv7)")
w("\tMOVW\t16(R13), R14")
w("\tMOVW\t8(R13), R12")
w("\tMOVW\t4(R13), R11")
for i in range(16):
    off = C_OFF[i] if i in C_OFF else 40 + 4 * i
    w(f"\tMOVW\t{off}(R13), R0")
    w(f"\tMOVW\t{4 * i}(R14), R1")
    w("\tADD\tR1, R0")
    w(f"\tMOVW\t{4 * i}(R12), R2")
    w("\tEOR\tR2, R0")
    w(f"\tMOVW\tR0, {4 * i}(R11)")
w("\tADD\t$64, R12")
w("\tMOVW\tR12, 8(R13)")
w("\tADD\t$64, R11")
w("\tMOVW\tR11, 4(R13)")
w("\tMOVW\t48(R14), R0")
w("\tADD\t$1, R0")
w("\tMOVW\tR0, 48(R14)")
w("\tMOVW\t12(R13), R0")
w("\tSUB.S\t$1, R0")
w("\tMOVW\tR0, 12(R13)")
w("\tBNE\tblock")
w("")
w("done:")
w("\tRET")

import sys
open(sys.argv[1], "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print("wrote", sys.argv[1], len(out), "lines")
