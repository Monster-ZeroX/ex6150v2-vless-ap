#!/usr/bin/env python3
"""Generate poly26_arm.s: Poly1305 block loop (26-bit limbs) for 32-bit ARM, Go asm syntax.

func poly26BlocksARM(h *[5]uint32, r *[9]uint32, msg *byte, blocks int)
r = [r0 r1 r2 r3 r4 s1 s2 s3 s4] (s_i = 5*r_i).

Registers: h0-h4 R0-R4, msg R5, 64-bit accumulator R6 (lo) R7 (hi), temps R8 R9 R12,
r pointer R11. R10 (g) is never touched. Products use UMULL/UMLAL (MULLU/MULALU).
Frame: 4 blocks left, 8 h ptr, 12..43 d1..d4 (lo, hi pairs).
"""
import sys

H = ["R0", "R1", "R2", "R3", "R4"]
R_OFF = {"r0": 0, "r1": 4, "r2": 8, "r3": 12, "r4": 16, "s1": 20, "s2": 24, "s3": 28, "s4": 32}
D_OFF = {1: 12, 2: 20, 3: 28, 4: 36}  # lo at off, hi at off+4

# columns: d_k = sum h_i * coef
COLS = {
    0: ["r0", "s4", "s3", "s2", "s1"],
    1: ["r1", "r0", "s4", "s3", "s2"],
    2: ["r2", "r1", "r0", "s4", "s3"],
    3: ["r3", "r2", "r1", "r0", "s4"],
    4: ["r4", "r3", "r2", "r1", "r0"],
}

out = []
w = out.append
w("// Code generated by gen_poly_arm.py for the EX6150v2 build. DO NOT EDIT.")
w("")
w("//go:build gc && !purego")
w("")
w('#include "textflag.h"')
w("")
w("// func poly26BlocksARM(h *[5]uint32, r *[9]uint32, msg *byte, blocks int)")
w("TEXT ·poly26BlocksARM(SB), NOSPLIT, $48-16")
w("\tMOVW\tblocks+12(FP), R0")
w("\tCMP\t$0, R0")
w("\tBEQ\tdone")
w("\tMOVW\tR0, 4(R13)")
w("\tMOVW\th+0(FP), R12")
w("\tMOVW\tR12, 8(R13)")
w("\tMOVW\tr+4(FP), R11")
w("\tMOVW\tmsg+8(FP), R5")
for i in range(5):
    w(f"\tMOVW\t{4 * i}(R12), {H[i]}")
w("")
w("loop:")
w("\t// h += m (26-bit limbs; x & mask26 done as (x<<6)>>6)")
w("\tMOVW\t0(R5), R8")
w("\tMOVW\tR8<<6, R9")
w("\tADD\tR9>>6, R0")
w("\tMOVW\t4(R5), R12")
w("\tMOVW\tR8>>26, R9")
w("\tORR\tR12<<6, R9")
w("\tMOVW\tR9<<6, R9")
w("\tADD\tR9>>6, R1")
w("\tMOVW\t8(R5), R8")
w("\tMOVW\tR12>>20, R9")
w("\tORR\tR8<<12, R9")
w("\tMOVW\tR9<<6, R9")
w("\tADD\tR9>>6, R2")
w("\tMOVW\t12(R5), R12")
w("\tMOVW\tR8>>14, R9")
w("\tORR\tR12<<18, R9")
w("\tMOVW\tR9<<6, R9")
w("\tADD\tR9>>6, R3")
w("\tADD\tR12>>8, R4")
w("\tADD\t$0x1000000, R4")


def column(k):
    coefs = COLS[k]
    lines = []
    for i, cname in enumerate(coefs):
        tmp = "R8" if i % 2 == 0 else "R9"
        lines.append(f"\tMOVW\t{R_OFF[cname]}(R11), {tmp}")
        op = "MULLU" if i == 0 else "MULALU"
        lines.append(f"\t{op}\t{tmp}, {H[i]}, (R7, R6)")
    return lines


w("\t// d1..d4 to the frame, d0 stays in R6:R7")
for k in (1, 2, 3, 4):
    out.extend(column(k))
    w(f"\tMOVW\tR6, {D_OFF[k]}(R13)")
    w(f"\tMOVW\tR7, {D_OFF[k] + 4}(R13)")
out.extend(column(0))
w("")
w("\t// carry chain: h_k = d_k & mask26, d_{k+1} += d_k >> 26")
for k in range(5):
    w(f"\tMOVW\tR6<<6, {H[k]}")
    w(f"\tMOVW\t{H[k]}>>6, {H[k]}")
    w("\tMOVW\tR6>>26, R8")
    w("\tORR\tR7<<6, R8")
    if k < 4:
        w(f"\tMOVW\t{D_OFF[k + 1]}(R13), R6")
        w(f"\tMOVW\t{D_OFF[k + 1] + 4}(R13), R7")
        w("\tADD.S\tR8, R6")
        w("\tADC\t$0, R7")
w("\t// h0 += 5*c; h1 += h0 >> 26")
w("\tADD\tR8<<2, R8")
w("\tADD\tR8, R0")
w("\tMOVW\tR0>>26, R8")
w("\tMOVW\tR0<<6, R0")
w("\tMOVW\tR0>>6, R0")
w("\tADD\tR8, R1")
w("")
w("\tADD\t$16, R5")
w("\tMOVW\t4(R13), R8")
w("\tSUB.S\t$1, R8")
w("\tMOVW\tR8, 4(R13)")
w("\tBNE\tloop")
w("")
w("\tMOVW\t8(R13), R12")
for i in range(5):
    w(f"\tMOVW\t{H[i]}, {4 * i}(R12)")
w("")
w("done:")
w("\tRET")

open(sys.argv[1], "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print("wrote", sys.argv[1], len(out), "lines")
